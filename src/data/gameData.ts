// 150 Planned Stages across the 5 Fantasy Kingdoms (30 per world)
export const LEVELS: LevelDefinition[] = Array.from({ length: 150 }, (_, idx) => {
  const level = idx + 1;
  let worldId: WorldId = 'clouds';
  if (level > 120) worldId = 'frozen';
  else if (level > 90) worldId = 'dragon';
  else if (level > 60) worldId = 'crystal';
  else if (level > 30) worldId = 'lava';

  const tierInWorld = ((level - 1) % 30) + 1;
  const worldNames: Record<WorldId, string> = {
    clouds: 'Sky Viaduct',
    lava: 'Magma Span',
    crystal: 'Crystal Express',
    dragon: 'Dragon Temple',
    frozen: 'Frost Peak',
  };

  return {
    level,
    worldId,
    title: `${worldNames[worldId]} ${tierInWorld}`,
    targetDistance: 220 + level * 42,
    targetCoins: 20 + Math.floor(level * 2.4),
    baseSpeed: Math.min(24 + level * 0.14, 43),
    maxSpeed: Math.min(36 + level * 0.18, 60),
    rewardCoins: 150 + level * 25,
    rewardGems: level % 5 === 0 ? 10 + Math.floor(level / 5) : 3,
    rewardXp: 80 + level * 15,
  };
});

